"""
Domain model for recommendations (FinOps + Green IT).

Why plain dataclass (not Pydantic):
- Domain purity: no framework dependency in this layer.
- Recommendations are output objects — generated by the recommendation_engine,
  consumed by the API adapter (which maps them to Pydantic DTOs).

Category and Severity are enums (stdlib) — they enforce valid values
without importing any external library.

WHY recommendation is an output object:
- The engine *generates* these. Adapters *translate* them.
- The domain never knows about HTTP, JSON, or API response shapes.
- Immutability: once generated, a recommendation is never mutated.
"""

from __future__ import annotations

from dataclasses import dataclass
from datetime import datetime
from enum import Enum
from uuid import UUID


class Category(str, Enum):
    """
    Recommendation category.

    WHY an enum: prevents free-text strings from leaking into domain logic.
    Each category maps to a specific metric set in metrics-reference.md.

    Values are str so they serialize to JSON without extra logic.
    """

    # FinOps categories
    COST_RIGHTSIZING = "cost_right-sizing"
    COST_ORPHANED_PVC = "cost_orphaned_pvc"
    COST_IDLE_RESOURCE = "cost_idle_resource"
    # V3: right-sizing from percentiles + validated forecast + variability (app.domain.ml)
    COST_RIGHTSIZING_ML = "cost_right-sizing_ml"

    # Green IT categories
    ENERGY_WASTE = "energy_waste"
    CARBON_INTENSITY = "carbon_intensity"

    # Cross-cutting
    DATA_QUALITY = "data_quality"
    # V3: statistically abnormal behaviour of a metric (investigate, not an action)
    ANOMALY = "anomaly"


class Severity(str, Enum):
    """
    Recommendation severity.

    WHY an enum: ensures valid values only. The engine assigns severity
    based on impact magnitude — the adapter never decides.
    """

    CRITICAL = "critical"
    WARNING = "warning"
    INFO = "info"


@dataclass(frozen=True)
class Recommendation:
    """
    A single actionable recommendation.

    Fields:
    - category: which bucket (finops vs green-it)
    - severity: how urgent (critical = act now, info = FYI)
    - namespace: primary scope (drill-down to pod/pvc is optional)
    - resource: specific resource name (pod name, PVC name, etc.)
    - message: human-readable explanation (defensible in oral exam)
    - current_value: what Prometheus reports right now
    - recommended_value: what the engine suggests
    - estimated_savings_kg_co2: carbon savings if implemented (nullable)
    - estimated_savings_usd: cost savings if implemented (nullable)

    WHY nullable savings:
    - Some recommendations have no calculable savings (e.g., data quality).
    - The API adapter can choose to omit or show "N/A" for these.

    WHY current_value and recommended_value are strings:
    - Values have heterogeneous units (%, bytes, hours, bool).
    - Storing as strings avoids a union type; the adapter formats for display.
    """

    # --- classification ---
    category: Category
    severity: Severity

    # --- scope ---
    namespace: str
    resource: str  # pod name, PVC name, or "cluster" for cluster-wide

    # --- explanation ---
    message: str

    # --- quantitative backing ---
    current_value: str
    recommended_value: str

    # --- optional impact (nullable = not always calculable) ---
    estimated_savings_kg_co2: float | None = None
    estimated_savings_usd: float | None = None

    # --- metadata ---
    timestamp: datetime | None = None

    # --- scope & attribution (V1) ---
    # WHY on the domain object: the MVP stored team="unknown" for every
    # recommendation because the domain object did not carry it. Chargeback
    # and per-cluster dashboards need these values end to end.
    cluster: str = "default"
    workload: str = "*"
    team: str = "unknown"
    cost_center: str = "unknown"
    environment: str = "unknown"

    # --- provenance (V1) ---
    # How the numbers behind this recommendation were obtained, e.g.
    # "energy: node_cpu_share (estimated)". None = direct measurement.
    estimation_method: str | None = None

    @property
    def fingerprint(self) -> str:
        """
        Stable identity of "the same advice about the same thing".

        WHY: the scheduler runs every 5 minutes. Without a fingerprint every
        cycle inserted a new PENDING row (~288 duplicates/day per advice).
        Storage uses this key to refresh an open recommendation instead.
        """
        return "|".join(
            (self.cluster, self.namespace, self.workload, self.category.value, self.resource)
        )


@dataclass(frozen=True)
class RecommendationSet:
    """
    Collection of recommendations for a namespace (or cluster).

    WHY: The engine returns a set, not individual recommendations.
    The adapter maps this to a list of Pydantic DTOs for the API response.

    WHY not a plain list:
    - Encapsulates metadata (generated_at, namespace) alongside the list.
    - Makes the engine contract explicit: always returns a set, never raw list.
    """

    namespace: str
    generated_at: datetime
    recommendations: tuple[Recommendation, ...]

    @property
    def total(self) -> int:
        """Count of recommendations in this set."""
        return len(self.recommendations)

    @property
    def critical_count(self) -> int:
        """Count of critical-severity recommendations."""
        return sum(1 for r in self.recommendations if r.severity == Severity.CRITICAL)

    @property
    def total_estimated_savings_usd(self) -> float:
        """
        Sum of USD savings across all recommendations.

        WHY: Gives a single number for "how much can we save?" in reports.
        """
        return sum(
            r.estimated_savings_usd
            for r in self.recommendations
            if r.estimated_savings_usd is not None
        )

    @property
    def total_estimated_savings_co2_kg(self) -> float:
        """
        Sum of CO2 savings across all recommendations.

        WHY: Green IT impact metric for sustainability reporting.
        """
        return sum(
            r.estimated_savings_kg_co2
            for r in self.recommendations
            if r.estimated_savings_kg_co2 is not None
        )

@dataclass(frozen=True)
class StoredRecommendation:
    """
    A recommendation as persisted: the domain advice + its lifecycle state.

    WHY a separate object (not fields on Recommendation):
    - Recommendation is what the ENGINE produces (immutable advice).
    - id/status/created_at/updated_at are assigned by storage and changed by humans.
    - The API needs both (the MVP returned fake UUID(int=i) ids because the
      port only returned the advice).
    """

    id: UUID
    status: str
    created_at: datetime
    updated_at: datetime
    recommendation: Recommendation
