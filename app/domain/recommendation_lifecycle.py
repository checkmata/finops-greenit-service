"""
Recommendation lifecycle — the human-in-the-loop state machine.

WHY in the domain (V1 fix):
- The MVP declared ALLOWED_TRANSITIONS in the router but never called it:
  an `executed` recommendation could be moved back to `pending`.
- Transition rules are business rules, so they live here, are pure, and are
  enforced by the API before any write.

States:
    pending   generated by the engine, awaiting a human
    approved  a human accepted it (nothing is executed automatically)
    rejected  a human declined it (terminal)
    executed  a human reports the change was applied (terminal)
    failed    applying it failed; can be re-approved or rejected
    obsolete  SYSTEM-only: a pending advice the engine no longer produces
              (condition resolved, e.g. requests fixed by hand). Never set
              through the API; terminal.

`dismissed` (MVP vocabulary) is migrated to `rejected` by 002_v1_multicluster.sql.
"""

from __future__ import annotations

from datetime import datetime, timedelta
from enum import Enum


class RecommendationStatus(str, Enum):
    PENDING = "pending"
    APPROVED = "approved"
    REJECTED = "rejected"
    EXECUTED = "executed"
    FAILED = "failed"
    OBSOLETE = "obsolete"


ALLOWED_TRANSITIONS: dict[RecommendationStatus, frozenset[RecommendationStatus]] = {
    RecommendationStatus.PENDING: frozenset({RecommendationStatus.APPROVED, RecommendationStatus.REJECTED}),
    RecommendationStatus.APPROVED: frozenset(
        {RecommendationStatus.EXECUTED, RecommendationStatus.FAILED, RecommendationStatus.REJECTED}
    ),
    RecommendationStatus.FAILED: frozenset({RecommendationStatus.APPROVED, RecommendationStatus.REJECTED}),
    RecommendationStatus.EXECUTED: frozenset(),
    RecommendationStatus.REJECTED: frozenset(),
    RecommendationStatus.OBSOLETE: frozenset(),
}
# Humans can never move anything TO obsolete (it is absent from every set above).

VALID_STATUSES: frozenset[str] = frozenset(s.value for s in RecommendationStatus)

# After a human rejects an advice, the scheduler must not re-create the very
# same advice 5 minutes later. It may come back after this cooldown.
REJECTION_COOLDOWN = timedelta(days=7)


def can_transition(current: str, new: str) -> bool:
    """True if `current → new` is allowed. Unknown statuses are never allowed."""
    if current not in VALID_STATUSES or new not in VALID_STATUSES:
        return False
    return RecommendationStatus(new) in ALLOWED_TRANSITIONS[RecommendationStatus(current)]


class UpsertAction(str, Enum):
    INSERT = "insert"
    REFRESH = "refresh"  # update values of the existing pending row
    SKIP = "skip"


def decide_upsert(
    existing_status: str | None,
    existing_updated_at: datetime | None,
    now: datetime,
) -> UpsertAction:
    """
    What the scheduler should do with a freshly generated advice, given the
    most recent stored advice with the same fingerprint.

    - none stored               → INSERT
    - pending                   → REFRESH (keep one row, update numbers)
    - approved / failed         → SKIP (a human is handling it)
    - rejected < cooldown ago   → SKIP (respect the human decision)
    - rejected ≥ cooldown ago   → INSERT (conditions persisted, ask again)
    - executed / obsolete       → INSERT (the condition is back → new advice)
    """
    if existing_status is None:
        return UpsertAction.INSERT
    if existing_status == RecommendationStatus.PENDING.value:
        return UpsertAction.REFRESH
    if existing_status in (RecommendationStatus.APPROVED.value, RecommendationStatus.FAILED.value):
        return UpsertAction.SKIP
    if existing_status == RecommendationStatus.REJECTED.value:
        if existing_updated_at is not None and now - existing_updated_at < REJECTION_COOLDOWN:
            return UpsertAction.SKIP
        return UpsertAction.INSERT
    return UpsertAction.INSERT
